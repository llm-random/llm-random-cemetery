#!/usr/bin/env python
"""Local driver for remote ctx eval submission.

Mirrors the run_exp.py flow: snapshot code to a temp branch, push to the cemetery,
ssh to the cluster, clone the branch, then in a tmux session run head-node setup
(which builds jobs.json + generates ctx_eval.job) followed by sbatch. Captures
the SLURM job ID and tails the log.
"""
import logging
import os
import sys
from pathlib import Path
from shlex import quote

import hydra
from omegaconf import OmegaConf

REPO_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO_ROOT))

from run_exp import (  # noqa: E402
    ConnectWithPassphrase,
    version_code,
    wait_for_job_id,
)
import resolver  # noqa: E402

logger = logging.getLogger(__name__)

CTX_EVAL_SCRIPT = "src/context_scaling/scripts/ctx_eval.py"
CTX_EVAL_SBATCH = "ctx_eval.job"  # generated by ctx_eval.py setup mode


def tmux_send(connection, session: str, line: str) -> None:
    connection.run(f"tmux send -t {session}.0 {quote(line)} ENTER")


@hydra.main(version_base=None, config_path="../../../configs", config_name="ctx_eval")
def submit_eval(cfg: OmegaConf):
    if cfg.infrastructure.server == "local":
        raise RuntimeError(
            "run_ctx_eval.py is for remote submission; "
            "run ctx_eval.py + sbatch directly for local."
        )

    branch = version_code(
        remote_url=cfg.infrastructure.git.remote_url,
        job_name=f"ctxeval_{cfg.eval.name}",
    )

    with ConnectWithPassphrase(
        host=cfg.infrastructure.server, inline_ssh_env=True
    ) as connection:
        cemetery_dir = cfg.infrastructure.cemetery_experiments_dir
        connection.run(f"mkdir -p {cemetery_dir}")
        experiment_dir = f"{cemetery_dir}/{branch}"

        if connection.run(f"test -d {experiment_dir}", warn=True).failed:
            connection.run(
                f"git clone --depth 1 -b {branch} "
                f"{cfg.infrastructure.git.remote_url} {experiment_dir}"
            )
        else:
            print(f"{experiment_dir} already exists; skipping clone.")

        try:
            connection.run(f"tmux new -d -s {branch}")
            tmux_send(connection, branch, f"cd {experiment_dir}")

            # forward real secrets (skip the resolver-emitted placeholder block)
            for var in resolver.ENV_VARS_TO_FORWARD:
                if var in os.environ:
                    tmux_send(connection, branch, f"export {var}={quote(os.environ[var])}")
                else:
                    logger.warning("%s not in local env; setup / job may fail.", var)

            # head-node env setup from cluster yaml (pixi activation, etc.)
            for line in OmegaConf.to_container(cfg.infrastructure.script, resolve=True):
                if "PLACEHOLDER" in line:
                    continue  # driver already exported the real secrets above
                tmux_send(connection, branch, line)
            tmux_send(connection, branch, 'export PYTHONPATH="$(pwd):${PYTHONPATH:-}"')

            # setup generates ctx_eval.job; sbatch submits it
            tmux_send(
                connection,
                branch,
                f"python {CTX_EVAL_SCRIPT} && sbatch {CTX_EVAL_SBATCH}",
            )

            job_id = wait_for_job_id(connection, branch, tries=120)
            print(f"Job ID: {job_id}")
            tmux_send(connection, branch, f"tail -f --retry slurm-{job_id}_0.out")

            if os.environ.get("LOGLEVEL", "WARNING").upper() == "DEBUG":
                connection.run(f"tmux attach-session -t {branch}", pty=True)
        except Exception as e:
            print("Exception while submitting eval: ", e)
            raise


if __name__ == "__main__":
    submit_eval()
